        static Dictionary<string, string> table;

        static Dictionary<string, string> Table()
        {
            if (table != null) return table;
            table = new Dictionary<string, string>();
            foreach (var r in Rows)
            {
                string key = r[0].Replace("{KA}", KA).Replace("{KZ}", KZ);
                string val = (LangIdx < r.Length ? r[LangIdx] : r[1]).Replace("{KA}", KA).Replace("{KZ}", KZ);
                table[key] = val;
            }
            return table;
        }

        // yuzde: tr "%85", fr/de "85 %", digerleri "85%"
        static string Pct(double v)
        {
            int n = (int)Math.Round(v);
            string c = Langs[LangIdx];
            if (c == "tr") return "%" + n;
            if (c == "fr" || c == "de") return n + " %";
            return n + "%";
        }

        static string L(string tr)
        {
            if (LangIdx == 0 || tr == null) return tr;
            int n;
            if (tr.Length > 1 && tr[0] == '%' && int.TryParse(tr.Substring(1), out n)) return Pct(n);
            string v;
            return Table().TryGetValue(tr, out v) ? v : tr;
        }

        // XAML'dan yuklenen pencerede tum metinleri cevir
        static void TranslateTree(DependencyObject o)
        {
            if (LangIdx == 0 || o == null) return;
            var tb = o as TextBlock;
            if (tb != null && tb.Text != null) tb.Text = L(tb.Text);
            var cc = o as ContentControl;
            if (cc != null && cc.Content is string) cc.Content = L((string)cc.Content);
            foreach (object child in LogicalTreeHelper.GetChildren(o))
            {
                var d = child as DependencyObject;
                if (d != null) TranslateTree(d);
            }
        }
